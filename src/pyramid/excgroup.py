"""Support for handling :mod:`exception groups <exceptions>` raised while
processing a request.

When an :class:`ExceptionGroup` (or :class:`BaseExceptionGroup`) bubbles up
through the request processing pipeline, :app:`Pyramid` normally treats it
like any other exception: a single :term:`exception view` registered for the
group's type (or :class:`Exception`) is invoked.  This module implements an
optional *exception group view* protocol, activated by registering an
aggregate view via
:meth:`pyramid.config.Configurator.add_exception_group_view`.  When active,
each *leaf* exception of the group is matched against the registered
exception views individually, and the aggregate view decides the final
response from the per-leaf results.

.. versionadded:: 2.2

"""

import builtins

from pyramid.response import Response

# Exception groups were added in Python 3.11.  On Python 3.10 these names
# do not exist; the names below are then ``None`` and the exception group
# view protocol is never activated.
BaseExceptionGroup = getattr(builtins, 'BaseExceptionGroup', None)
ExceptionGroup = getattr(builtins, 'ExceptionGroup', None)


class LeafResult:
    """Information about a single leaf exception of an exception group.

    ``leaf``

        The leaf exception instance.

    ``path``

        A tuple of the exception groups containing the leaf, ordered from
        the outermost group (the exception that was originally raised) to
        the leaf's immediate parent group.

    ``response``

        The :term:`response` generated by the :term:`exception view` that
        handled the leaf, or ``None`` if no exception view matched it.

    .. versionadded:: 2.2

    """

    def __init__(self, leaf, path, response=None):
        self.leaf = leaf
        self.path = path
        self.response = response

    def __repr__(self):
        return '<LeafResult %r at 0x%x>' % (self.leaf, id(self))


class ExceptionGroupResults:
    """The per-leaf results of rendering exception views for the leaves of
    an exception group.

    An instance of this class is passed as the first argument to an
    :term:`exception group view`.

    ``group``

        The original exception group that was raised.

    ``leaves``

        A list of :class:`LeafResult` objects, one per leaf exception of
        ``group``, in depth-first traversal order.

    .. versionadded:: 2.2

    """

    def __init__(self, group, leaves):
        self.group = group
        self.leaves = leaves

    @property
    def matched(self):
        """The subset of :attr:`leaves` which were handled by an exception
        view (i.e. whose ``response`` is not ``None``)."""
        return [
            result for result in self.leaves if result.response is not None
        ]

    @property
    def unmatched(self):
        """The subset of :attr:`leaves` which no exception view matched."""
        return [result for result in self.leaves if result.response is None]

    def derive_unmatched(self):
        """Return a new exception group containing only the unmatched leaf
        exceptions, preserving the nesting structure of the original group,
        or ``None`` if every leaf was matched.

        The leaf exceptions themselves are the original objects, so their
        tracebacks and ``__cause__`` / ``__context__`` chains are left
        intact.
        """
        unmatched_ids = {id(result.leaf) for result in self.unmatched}
        if not unmatched_ids:
            return None
        unmatched, _rest = self.group.split(
            lambda exc: id(exc) in unmatched_ids
        )
        return unmatched


def walk_leaves(group):
    """Iterate over the leaf exceptions of an exception group.

    Yields ``(leaf, path)`` tuples in depth-first traversal order, where
    ``path`` is a tuple of the exception groups containing the leaf, ordered
    from the outermost group to the leaf's immediate parent group.

    .. versionadded:: 2.2

    """

    def _walk(node, path):
        for exc in node.exceptions:
            if BaseExceptionGroup is not None and isinstance(
                exc, BaseExceptionGroup
            ):
                yield from _walk(exc, path + (node,))
            else:
                yield exc, path + (node,)

    yield from _walk(group, ())


def default_exception_group_view(results, request):
    """The default :term:`exception group view`.

    It decides the final response for an exception group from the per-leaf
    :class:`results <ExceptionGroupResults>` as follows:

    - If any leaf exceptions were not matched by an exception view, they
      are reraised as a group derived from the original exception group
      (see :meth:`ExceptionGroupResults.derive_unmatched`), with the
      original group as their ``__cause__``, so that upstream handlers can
      deal with them.  In particular, leaves which are not instances of
      :class:`Exception` (such as :class:`asyncio.CancelledError` or
      :class:`KeyboardInterrupt`) are never converted into an HTTP error
      response.

    - If every matched leaf produced a response with the same status code,
      the first response is returned.

    - Otherwise, rather than arbitrarily picking one leaf's status code, a
      ``500 Internal Server Error`` response describing the conflicting
      statuses is returned.

    .. versionadded:: 2.2

    """
    unmatched = results.unmatched
    if unmatched:
        derived = results.derive_unmatched()
        derived.__cause__ = results.group
        raise derived

    matched = results.matched
    statuses = {result.response.status_code for result in matched}
    if len(statuses) == 1:
        return matched[0].response

    detail = '\n'.join(
        ['exception group leaves produced conflicting response statuses:']
        + [
            '  %r -> %s' % (result.leaf, result.response.status)
            for result in matched
        ]
    )
    return Response(status=500, text=detail, content_type='text/plain')
